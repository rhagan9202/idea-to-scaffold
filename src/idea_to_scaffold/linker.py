"""Cross-link a planning package so agents can traverse it and drift is visible.

`its link` does three things, all idempotent:

1. **ID links.** Every bare ID reference (``FR-003``) in a planning doc becomes a relative link to where the ID is
   defined (``[FR-003](03-requirements.md#fr-003--check-in-for-today)``). Existing ID links are re-pointed if the
   definition moved or its heading changed. Headings, code blocks and inline code are left alone.
2. **Nav blocks.** Each planning doc gets a generated block under its title with links to the planning index, the
   docs it depends on, the next doc in reading order, and the docs that reference it (backlinks).
3. **Planning index.** ``planning/README.md`` is regenerated: reading order with live statuses, decisions,
   wireframes, where every ID is defined, and a backlog summary.

With ``check=True`` nothing is written; the list of files that *would* change is returned. A non-empty list means the
docs have drifted from their links, which CI can fail on.
"""
from __future__ import annotations

import os
import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from .ids import (
    ID_PATTERN,
    ID_RE,
    KIND_EXAMPLES,
    KIND_LABELS,
    META_FILES,
    OWNERS,
    field_value,
    github_slug,
    id_kind,
    owned_by,
    scan_lines,
    sections,
    strip_links,
)
from .package import BACKLOG_STATUSES, READING_ORDER, Package, parse_front_matter

NAV_START = "<!-- its:nav (generated by `its link`; do not edit) -->"
NAV_END = "<!-- /its:nav -->"
NAV_BLOCK_RE = re.compile(r"\n?<!-- its:nav[^>]*-->.*?<!-- /its:nav -->\n?", re.DOTALL)
INDEX_MARKER = "<!-- generated by idea-to-scaffold (`its link`); do not edit by hand -->"
TOKEN_RE = re.compile(rf"(`[^`\n]*`)|\[([^\]\n]*)\]\(([^)\s]*)\)|(?<![\w/#\[-])({ID_PATTERN})(?![\w-])")
FRONT_RE = re.compile(r"\A---\s*\n.*?\n---\s*\n", re.DOTALL)


@dataclass(frozen=True)
class Target:
    rel: str              # logical path of the defining file
    anchor: str | None    # heading slug inside it, if any
    own_heading: bool = False  # the ID has its own heading (or file), so same-doc links are useful


@dataclass
class Doc:
    rel: str
    path: Path
    front: str   # raw front matter including fences ("" if none)
    meta: dict
    body: str


def _load_docs(pkg: Package) -> dict[str, Doc]:
    docs: dict[str, Doc] = {}
    for path in pkg.planning_files():
        rel = pkg.rel(path)
        if rel in META_FILES:
            continue
        text = path.read_text(encoding="utf-8")
        m = FRONT_RE.match(text)
        front = m.group(0) if m else ""
        meta, _ = parse_front_matter(text)
        docs[rel] = Doc(rel, path, front, meta, text[len(front):])
    return docs


def build_index(pkg: Package, docs: dict[str, Doc] | None = None) -> dict[str, Target]:
    """Map every defined ID to where it is defined."""
    docs = docs if docs is not None else _load_docs(pkg)
    index: dict[str, Target] = {}
    heading_defined: set[str] = set()
    for rel, doc in sorted(docs.items()):
        if rel.startswith("planning/adr/") and doc.meta.get("id"):
            index[str(doc.meta["id"])] = Target(rel, None, True)
            heading_defined.add(str(doc.meta["id"]))
        if rel.startswith("planning/wireframes/") and re.fullmatch(r"S-[a-z0-9-]+", Path(rel).stem):
            index[Path(rel).stem] = Target(rel, None, True)
            heading_defined.add(Path(rel).stem)
        for line in scan_lines(doc.body):
            if line.in_code:
                continue
            for m in ID_RE.finditer(strip_links(line.text)):
                ident = m.group(1)
                if not owned_by(id_kind(ident), rel) or ident in heading_defined:
                    continue
                if line.heading is not None and ID_RE.match(line.heading.strip()):
                    if ID_RE.match(line.heading.strip()).group(1) == ident:
                        index[ident] = Target(rel, github_slug(line.heading), True)
                        heading_defined.add(ident)
                        continue
                if ident not in index:
                    index[ident] = Target(rel, github_slug(line.section) if line.section else None)
    return index


def _href(from_rel: str, target: Target, pkg: Package) -> str:
    if target.rel == from_rel and target.anchor:
        return f"#{target.anchor}"
    src = pkg.path_of(from_rel).parent
    dst = pkg.path_of(target.rel)
    path = Path(os.path.relpath(dst, src)).as_posix()
    return f"{path}#{target.anchor}" if target.anchor else path


def _link_body(pkg: Package, rel: str, body: str, index: dict[str, Target]) -> str:
    out_lines = body.split("\n")
    for line in scan_lines(body):
        if line.in_code or line.heading is not None or NAV_START[:12] in line.text:
            continue

        def repl(m: re.Match) -> str:
            if m.group(1):  # inline code
                return m.group(0)
            if m.group(2) is not None:  # existing link
                text = m.group(2)
                if ID_RE.fullmatch(text) and text in index:
                    target = index[text]
                    if target.rel == rel and not target.own_heading:
                        return text
                    return f"[{text}]({_href(rel, target, pkg)})"
                return m.group(0)
            ident = m.group(4)
            target = index.get(ident)
            if target is None or (target.rel == rel and not (target.own_heading and target.anchor)):
                return ident
            return f"[{ident}]({_href(rel, target, pkg)})"

        out_lines[line.number] = TOKEN_RE.sub(repl, line.text)
    return "\n".join(out_lines)


def _references(docs: dict[str, Doc], index: dict[str, Target]) -> dict[str, set[str]]:
    """rel -> set of other rels that reference IDs defined in it."""
    refs: dict[str, set[str]] = {}
    for rel, doc in docs.items():
        for line in scan_lines(NAV_BLOCK_RE.sub("\n", doc.body)):
            if line.in_code:
                continue
            for m in ID_RE.finditer(strip_links(line.text)):
                target = index.get(m.group(1))
                if target and target.rel != rel:
                    refs.setdefault(target.rel, set()).add(rel)
    return refs


def _title(doc: Doc) -> str:
    return str(doc.meta.get("title") or Path(doc.rel).stem)


def _nav(pkg: Package, doc: Doc, docs: dict[str, Doc], refs: dict[str, set[str]]) -> str:
    by_id = {str(d.meta.get("id")): d for d in docs.values() if d.meta.get("id")}

    def link(other: Doc) -> str:
        return f"[{_title(other)}]({_href(doc.rel, Target(other.rel, None), pkg)})"

    index_href = _href(doc.rel, Target("planning/README.md", None), pkg)
    parts = [f"**Index:** [Planning index]({index_href})"]
    deps = doc.meta.get("depends_on") or []
    if isinstance(deps, str):
        deps = [deps]
    up = [link(by_id[str(d)]) for d in deps if str(d) in by_id]
    if up:
        parts.append("**Upstream:** " + ", ".join(up))
    if doc.rel in READING_ORDER:
        later = [r for r in READING_ORDER[READING_ORDER.index(doc.rel) + 1:] if r in docs]
        if later:
            parts.append("**Next:** " + link(docs[later[0]]))
    lines = [NAV_START, "> " + " · ".join(parts)]
    back = sorted(refs.get(doc.rel, set()), key=lambda r: (READING_ORDER.index(r) if r in READING_ORDER else 99, r))
    if back:
        lines.append(">")
        lines.append("> **Referenced by:** " + ", ".join(link(docs[r]) for r in back))
    lines.append(NAV_END)
    return "\n".join(lines)


def _with_nav(body: str, nav: str) -> str:
    body = NAV_BLOCK_RE.sub("\n", body, count=1)
    lines = body.split("\n")
    for line in scan_lines(body):
        if line.in_code:
            continue
        if line.heading is not None and line.text.startswith("# "):
            i = line.number
            rest = lines[i + 1:]
            while rest and rest[0].strip() == "":
                rest.pop(0)
            return "\n".join(lines[: i + 1] + ["", nav, ""] + rest)
    stripped = body.lstrip("\n")
    return f"{nav}\n\n{stripped}"


def backlog_items(pkg: Package) -> list[dict[str, str]]:
    """Parse the backlog into a list of {id, title, milestone, status, satisfies, depends}."""
    path = pkg.path_of("planning/07-backlog.md")
    if not path.is_file():
        return []
    _, body = parse_front_matter(path.read_text(encoding="utf-8"))
    items = []
    for heading, section in sections(body):
        m = re.match(r"(T-\d+\.\d+)\b\s*(?:[—–:-]+\s*)?(.*)", strip_links(heading))
        if not m:
            continue
        get = lambda name: strip_links(field_value(section, name) or "").strip()  # noqa: E731
        items.append({
            "id": m.group(1),
            "title": m.group(2).strip(),
            "milestone": get("Milestone"),
            "status": get("Status").lower(),
            "satisfies": get("Satisfies"),
            "depends": get("Depends on"),
        })
    return items


def _index_md(pkg: Package, docs: dict[str, Doc], index: dict[str, Target]) -> str:
    def href(rel: str, anchor: str | None = None) -> str:
        return _href("planning/README.md", Target(rel, anchor), pkg)

    out = [INDEX_MARKER, f"# Planning index — {pkg.name}", "", pkg.summary, ""]
    out += [
        "Start here. Read the documents in order; each one links to what it depends on and what references it.",
        "Documents with status **approved** are binding for agents; **draft** and **review** are guidance.",
        "",
        "| # | Document | Status | Defines | Depends on |",
        "| - | -------- | ------ | ------- | ---------- |",
    ]
    by_id = {str(d.meta.get("id")): d for d in docs.values()}
    for n, rel in enumerate(r for r in READING_ORDER if r in docs):
        doc = docs[rel]
        kinds = [k for k, owners in OWNERS.items() if rel in owners]
        defines = ", ".join(f"{KIND_LABELS[k]}s (`{KIND_EXAMPLES[k]}`)" for k in kinds) or "—"
        deps = doc.meta.get("depends_on") or []
        deps = [deps] if isinstance(deps, str) else deps
        dep_links = ", ".join(
            f"[{_title(by_id[str(d)])}]({href(by_id[str(d)].rel)})" for d in deps if str(d) in by_id
        ) or "—"
        out.append(
            f"| {n} | [{_title(doc)}]({href(rel)}) | {doc.meta.get('status', '?')} | {defines} | {dep_links} |"
        )

    adrs = sorted(r for r in docs if r.startswith("planning/adr/"))
    if adrs:
        out += ["", "## Decisions", ""]
        out += [f"- [{_title(docs[r])}]({href(r)}) — {docs[r].meta.get('status', '?')}" for r in adrs]
    frames = sorted(r for r in docs if r.startswith("planning/wireframes/"))
    if frames:
        out += ["", "## Wireframes", ""]
        out += [f"- [{_title(docs[r])}]({href(r)})" for r in frames]

    items = backlog_items(pkg)
    if items:
        counts = Counter(i["status"] or "?" for i in items)
        order = BACKLOG_STATUSES + sorted(set(counts) - set(BACKLOG_STATUSES))
        out += ["", "## Backlog summary", "",
                f"The [backlog]({href('planning/07-backlog.md')}) is the only list of work items.", "",
                "| Status | Items |", "| ------ | ----- |"]
        for status in order:
            if counts.get(status):
                ids = ", ".join(i["id"] for i in items if (i["status"] or "?") == status)
                out.append(f"| {status} | {counts[status]}: {ids} |")
        nxt = next((i for i in items if i["status"] == "todo"), None)
        if nxt:
            anchor = index.get(nxt["id"])
            out += ["", f"**Next up:** [{nxt['id']} — {nxt['title']}]({href(anchor.rel, anchor.anchor) if anchor else href('planning/07-backlog.md')})"]

    if index:
        out += ["", "## Where each ID is defined", "", "| ID | Kind | Defined in |", "| -- | ---- | ---------- |"]

        def sort_key(ident: str) -> tuple:
            kind = id_kind(ident)
            order = list(OWNERS).index(kind)
            nums = [int(x) for x in re.findall(r"\d+", ident)]
            return (order, nums, ident)

        for ident in sorted(index, key=sort_key):
            t = index[ident]
            out.append(f"| [{ident}]({href(t.rel, t.anchor)}) | {KIND_LABELS[id_kind(ident)]} | {_title(docs[t.rel])} |")

    out += [
        "",
        "## Keeping the docs in sync",
        "",
        "- Every ID is defined in exactly one place (see the table above). Elsewhere, refer to it by ID only.",
        "- Work items live only in the backlog. Don't keep task lists in other docs, issues or code comments.",
        "- When you finish or start work, change the item's **Status** in the backlog in the same commit.",
        "- After editing any planning doc, run `its link` then `its validate` (CI runs `its link --check`).",
        "- Changes to approved docs go through the update-plan playbook.",
        "",
    ]
    return "\n".join(out)


def link_package(pkg: Package, *, check: bool = False) -> list[str]:
    """Link the package in place. Returns the logical paths that changed (or would change, with check=True)."""
    docs = _load_docs(pkg)
    index = build_index(pkg, docs)
    refs = _references(docs, index)
    changed: list[str] = []
    for rel, doc in sorted(docs.items()):
        body = _link_body(pkg, rel, doc.body, index)
        body = _with_nav(body, _nav(pkg, doc, docs, refs))
        if not body.endswith("\n"):
            body += "\n"
        new = doc.front + body
        if new != doc.path.read_text(encoding="utf-8"):
            changed.append(rel)
            if not check:
                doc.path.write_text(new, encoding="utf-8")
    readme = pkg.path_of("planning/README.md")
    content = _index_md(pkg, docs, index)
    if not readme.is_file() or readme.read_text(encoding="utf-8") != content:
        changed.append("planning/README.md")
        if not check:
            readme.parent.mkdir(parents=True, exist_ok=True)
            readme.write_text(content, encoding="utf-8")
    return changed
