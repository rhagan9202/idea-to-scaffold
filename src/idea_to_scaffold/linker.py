"""Cross-link a planning package so agents can traverse it and drift is visible.

`its link` does four things, all idempotent:

1. **ID links.** Every bare ID reference (``FR-003``) in a planning doc becomes a relative link to where the ID is
   defined (``[FR-003](03-requirements.md#fr-003--check-in-for-today)``). Existing ID links are re-pointed if the
   definition moved or its heading changed. Headings, code blocks and inline code are left alone.
2. **Nav blocks.** Each planning doc gets a generated block under its title with links to the planning index, the
   docs it depends on, the next doc in reading order, and the docs that reference it (backlinks).
3. **Planning index.** ``planning/README.md`` is regenerated: reading order with each doc's status, decisions,
   wireframes and where every ID is defined. It carries no backlog status, which `its next` answers live.
4. **Commands.** The blocks between ``its:commands`` markers in AGENTS.md, HANDOFF.md and the CI workflow are
   rewritten from package.yaml, its one source (see `blocks.py`).

With ``check=True`` nothing is written; the list of files that *would* change is returned. A non-empty list means the
docs have drifted from their links, which CI can fail on.
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass
from pathlib import Path

from .blocks import sync as sync_blocks
from .ids import (
    ID_PATTERN,
    ID_RE,
    KIND_LABELS,
    META_FILES,
    OWNERS,
    STRICT_KINDS,
    definition_on_line,
    id_kind,
    owned_by,
    scan_lines,
    strip_links,
    trace_field_spans,
)
from .package import READING_ORDER, Package, parse_front_matter

NAV_START = "<!-- its:nav (generated by `its link`; do not edit) -->"
NAV_END = "<!-- /its:nav -->"
NAV_BLOCK_RE = re.compile(r"\n?<!-- its:nav[^>]*-->.*?<!-- /its:nav -->\n?", re.DOTALL)
INDEX_MARKER = "<!-- generated by idea-to-scaffold (`its link`); do not edit by hand -->"
# Tokens on a line, in order of precedence: things left alone (inline code of any backtick length, HTML comments,
# images), existing links (re-pointed only when they are ID links into the package), then bare IDs.
TOKEN_RE = re.compile(
    r"(?P<skip>(?P<ticks>`+)[^\n]*?(?<!`)(?P=ticks)(?!`)|<!--.*?-->|!\[[^\]\n]*\]\([^)\n]*\))"
    r"|\[(?P<text>[^\]\n]*)\]\((?P<href>[^)\s]*)\)"
    rf"|(?<![\w/#\[-])(?P<id>{ID_PATTERN})(?![\w-])"
)
SCHEME_RE = re.compile(r"^[a-z][a-z0-9+.-]*:", re.IGNORECASE)


def _is_package_link(href: str) -> bool:
    """A link `its link` may re-point: a same-doc anchor or a relative link to a Markdown file. External URLs and
    links to other kinds of files belong to the author."""
    if SCHEME_RE.match(href) or href.startswith("/"):
        return False
    path = href.partition("#")[0]
    return path == "" or path.endswith(".md")
FRONT_RE = re.compile(r"\A---\s*\n.*?\n---\s*\n", re.DOTALL)


@dataclass(frozen=True)
class Target:
    rel: str              # logical path of the defining file
    anchor: str | None    # heading slug inside it, if any
    own_heading: bool = False  # the ID has its own heading (or file), so same-doc links are useful


@dataclass
class Doc:
    rel: str
    path: Path
    front: str   # raw front matter including fences ("" if none)
    meta: dict
    body: str


def _load_docs(pkg: Package) -> dict[str, Doc]:
    docs: dict[str, Doc] = {}
    for path in pkg.planning_files():
        rel = pkg.rel(path)
        if rel in META_FILES:
            continue
        text = path.read_text(encoding="utf-8")
        m = FRONT_RE.match(text)
        front = m.group(0) if m else ""
        meta, _ = parse_front_matter(text)
        docs[rel] = Doc(rel, path, front, meta, text[len(front):])
    return docs


@dataclass
class Scan:
    index: dict[str, Target]                     # ID -> where it is defined
    definitions: dict[str, list[tuple[str, bool]]]  # ID -> [(rel, is_heading)] for every definition site
    references: dict[str, set[str]]              # ID -> files that reference it (definite references only)


def scan_package(pkg: Package, docs: dict[str, Doc] | None = None) -> Scan:
    """Find where every ID is defined and where it is referenced.

    A definition is a heading starting with the ID, a table row whose first cell is the ID, a line starting with the
    ID in bold, an ADR's front-matter id, or a wireframe file named after a screen ID, in the file that owns that kind
    of ID. Anything else is a reference. Ambiguous kinds (``M1``, ``C-x``, ``S-x``, ``F-nn``, ``G-n``) only count as
    references when defined, or when they sit in a traceability field (``**Supports:** G-1``), so prose like
    "M1 Mac" or "C-suite" is ignored.
    """
    docs = docs if docs is not None else _load_docs(pkg)
    index: dict[str, Target] = {}
    definitions: dict[str, list[tuple[str, bool]]] = {}
    candidates: list[tuple[str, str, bool]] = []  # (ident, rel, definite)

    def define(ident: str, target: Target, heading: bool) -> None:
        definitions.setdefault(ident, []).append((target.rel, heading))
        current = index.get(ident)
        if current is None or (target.own_heading and not current.own_heading):
            index[ident] = target

    for rel, doc in sorted(docs.items()):
        if rel.startswith("planning/adr/") and doc.meta.get("id"):
            define(str(doc.meta["id"]), Target(rel, None, True), False)
        if rel.startswith("planning/wireframes/") and re.fullmatch(r"S-[a-z0-9]+(?:-[a-z0-9]+)*", Path(rel).stem):
            define(Path(rel).stem, Target(rel, None, True), False)
        for line in scan_lines(doc.body):
            text = strip_links(line.text)
            defined_here = definition_on_line(line)
            if defined_here and owned_by(id_kind(defined_here), rel):
                if line.heading is not None:
                    define(defined_here, Target(rel, line.anchor, True), True)
                else:
                    anchor = line.section_anchor
                    define(defined_here, Target(rel, anchor), False)
            else:
                defined_here = None
            spans = trace_field_spans(text)
            for m in ID_RE.finditer(text):
                ident = m.group(1)
                if ident == defined_here and m.start() == text.find(ident):
                    continue
                in_field = any(a <= m.start() < b for a, b in spans)
                candidates.append((ident, rel, in_field or id_kind(ident) in STRICT_KINDS))

    references: dict[str, set[str]] = {}
    for ident, rel, definite in candidates:
        if definite or ident in index:
            references.setdefault(ident, set()).add(rel)
    return Scan(index, definitions, references)


def build_index(pkg: Package, docs: dict[str, Doc] | None = None) -> dict[str, Target]:
    """Map every defined ID to where it is defined."""
    return scan_package(pkg, docs).index


def _href(from_rel: str, target: Target, pkg: Package) -> str:
    if target.rel == from_rel and target.anchor:
        return f"#{target.anchor}"
    src = pkg.path_of(from_rel).parent
    dst = pkg.path_of(target.rel)
    path = Path(os.path.relpath(dst, src)).as_posix()
    return f"{path}#{target.anchor}" if target.anchor else path


def _link_body(pkg: Package, rel: str, body: str, index: dict[str, Target]) -> str:
    out_lines = body.split("\n")
    for line in scan_lines(body):
        if line.in_code or line.heading is not None or NAV_START[:12] in line.text:
            continue

        def repl(m: re.Match) -> str:
            if m.group("skip"):  # inline code, HTML comment or image
                return m.group(0)
            if m.group("text") is not None:  # existing link
                text = m.group("text")
                if ID_RE.fullmatch(text) and text in index and _is_package_link(m.group("href")):
                    target = index[text]
                    if target.rel == rel and not target.own_heading:
                        return text
                    return f"[{text}]({_href(rel, target, pkg)})"
                return m.group(0)
            ident = m.group("id")
            target = index.get(ident)
            if target is None or (target.rel == rel and not (target.own_heading and target.anchor)):
                return ident
            return f"[{ident}]({_href(rel, target, pkg)})"

        out_lines[line.number] = TOKEN_RE.sub(repl, line.text)
    return "\n".join(out_lines)


def _references(docs: dict[str, Doc], index: dict[str, Target]) -> dict[str, set[str]]:
    """rel -> set of other rels that reference IDs defined in it."""
    refs: dict[str, set[str]] = {}
    for rel, doc in docs.items():
        for line in scan_lines(NAV_BLOCK_RE.sub("\n", doc.body)):
            if line.in_code:
                continue
            for m in ID_RE.finditer(strip_links(line.text)):
                target = index.get(m.group(1))
                if target and target.rel != rel:
                    refs.setdefault(target.rel, set()).add(rel)
    return refs


def _title(doc: Doc) -> str:
    return str(doc.meta.get("title") or Path(doc.rel).stem)


def _nav(pkg: Package, doc: Doc, docs: dict[str, Doc], refs: dict[str, set[str]]) -> str:
    by_id = {str(d.meta.get("id")): d for d in docs.values() if d.meta.get("id")}

    def link(other: Doc) -> str:
        return f"[{_title(other)}]({_href(doc.rel, Target(other.rel, None), pkg)})"

    index_href = _href(doc.rel, Target("planning/README.md", None), pkg)
    parts = [f"**Index:** [Planning index]({index_href})"]
    deps = doc.meta.get("depends_on") or []
    if isinstance(deps, str):
        deps = [deps]
    up = [link(by_id[str(d)]) for d in deps if str(d) in by_id]
    if up:
        parts.append("**Upstream:** " + ", ".join(up))
    if doc.rel in READING_ORDER:
        later = [r for r in READING_ORDER[READING_ORDER.index(doc.rel) + 1:] if r in docs]
        if later:
            parts.append("**Next:** " + link(docs[later[0]]))
    lines = [NAV_START, "> " + " · ".join(parts)]
    back = sorted(refs.get(doc.rel, set()), key=lambda r: (READING_ORDER.index(r) if r in READING_ORDER else 99, r))
    if back:
        lines.append(">")
        lines.append("> **Referenced by:** " + ", ".join(link(docs[r]) for r in back))
    lines.append(NAV_END)
    return "\n".join(lines)


def _with_nav(body: str, nav: str) -> str:
    body = NAV_BLOCK_RE.sub("\n", body, count=1)
    lines = body.split("\n")
    for line in scan_lines(body):
        if line.in_code:
            continue
        if line.heading is not None and line.text.startswith("# "):
            i = line.number
            rest = lines[i + 1:]
            while rest and rest[0].strip() == "":
                rest.pop(0)
            return "\n".join(lines[: i + 1] + ["", nav, ""] + rest)
    stripped = body.lstrip("\n")
    return f"{nav}\n\n{stripped}"


def _id_sort_key(ident: str) -> tuple:
    kind = id_kind(ident)
    order = list(OWNERS).index(kind)
    nums = [int(x) for x in re.findall(r"\d+", ident)]
    return (order, nums, ident)


def _defines(kind: str, rel: str, index: dict[str, Target]) -> str:
    """`Goals (G-1 to G-3)`: the IDs of one kind this doc actually defines."""
    ids = sorted((i for i, t in index.items() if t.rel == rel and id_kind(i) == kind), key=_id_sort_key)
    label = f"{KIND_LABELS[kind]}s"
    if not ids:
        return label
    if len(ids) == 1:
        return f"{label} ({ids[0]})"
    if kind in ("C", "S"):  # named, not numbered: list them
        shown = ", ".join(ids[:4])
        return f"{label} ({shown}{f' and {len(ids) - 4} more' if len(ids) > 4 else ''})"
    if len(ids) == 2:
        return f"{label} ({ids[0]}, {ids[1]})"
    return f"{label} ({ids[0]} to {ids[-1]})"


def _index_md(pkg: Package, docs: dict[str, Doc], index: dict[str, Target]) -> str:
    def href(rel: str, anchor: str | None = None) -> str:
        return _href("planning/README.md", Target(rel, anchor), pkg)

    out = [INDEX_MARKER, f"# Planning index — {pkg.name}", "", pkg.summary, ""]
    out += [
        "Start here. Read the documents in order; each one links to what it depends on and what references it.",
        "Documents with status **approved** are binding for agents; **draft** and **review** are guidance.",
        "",
        "| # | Document | Status | Defines | Depends on |",
        "| - | -------- | ------ | ------- | ---------- |",
    ]
    by_id = {str(d.meta.get("id")): d for d in docs.values()}
    for n, rel in enumerate(r for r in READING_ORDER if r in docs):
        doc = docs[rel]
        kinds = [k for k, owners in OWNERS.items() if rel in owners]
        defines = ", ".join(_defines(k, rel, index) for k in kinds) or "—"
        deps = doc.meta.get("depends_on") or []
        deps = [deps] if isinstance(deps, str) else deps
        dep_links = ", ".join(
            f"[{_title(by_id[str(d)])}]({href(by_id[str(d)].rel)})" for d in deps if str(d) in by_id
        ) or "—"
        out.append(
            f"| {n} | [{_title(doc)}]({href(rel)}) | {doc.meta.get('status', '?')} | {defines} | {dep_links} |"
        )

    adrs = sorted(r for r in docs if r.startswith("planning/adr/"))
    if adrs:
        out += ["", "## Decisions", ""]
        out += [f"- [{_title(docs[r])}]({href(r)}) — {docs[r].meta.get('status', '?')}" for r in adrs]
    frames = sorted(r for r in docs if r.startswith("planning/wireframes/"))
    if frames:
        out += ["", "## Wireframes", ""]
        out += [f"- [{_title(docs[r])}]({href(r)})" for r in frames]

    if pkg.path_of("planning/07-backlog.md").is_file():
        # No live status here: statuses change on every task branch, so a committed summary would go stale and
        # conflict on parallel merges. `its next` and `its backlog` answer it live.
        out += ["", "## Backlog", "",
                f"The [backlog]({href('planning/07-backlog.md')}) is the only list of work items. "
                "Run `its next` for the next ready item, or `its backlog` for every item's status."]

    if index:
        out += ["", "## Where each ID is defined", "", "| ID | Kind | Defined in |", "| -- | ---- | ---------- |"]

        for ident in sorted(index, key=_id_sort_key):
            t = index[ident]
            out.append(f"| [{ident}]({href(t.rel, t.anchor)}) | {KIND_LABELS[id_kind(ident)]} | {_title(docs[t.rel])} |")

    out += [
        "",
        "## Keeping the docs in sync",
        "",
        "- Every ID is defined in exactly one place (see the table above). Elsewhere, refer to it by ID only.",
        "- Work items live only in the backlog. Don't keep task lists in other docs, issues or code comments.",
        "- Start and finish items with `its start <ID>` and `its done <ID>`, or change the item's **Status** in the "
        "backlog in the same commit as the work.",
        "- After editing any planning doc, run `its link` then `its validate` (`its link --check` exits 8 if links are stale).",
        "- Changes to approved docs go through the update-plan playbook. `its show <ID>` lists the docs that mention an ID.",
        "",
    ]
    return "\n".join(out)


def _read_raw(path: Path) -> str | None:
    """A file's text with its line endings as they are on disk."""
    try:
        with open(path, encoding="utf-8", newline="") as fh:
            return fh.read()
    except FileNotFoundError:
        return None


def _write_raw(path: Path, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)


def link_package(pkg: Package, *, check: bool = False, adopt: bool = False, commands: bool = False) -> list[str]:
    """Link the package in place. Returns the logical paths that changed (or would change, with check=True).
    `commands` also rewrites the generated command blocks (blocks.py), as `its link` and scaffold do, and `adopt`
    puts their markers around a command list that has none."""
    docs = _load_docs(pkg)
    index = build_index(pkg, docs)
    refs = _references(docs, index)
    changed: list[str] = []
    for rel, doc in sorted(docs.items()):
        body = _link_body(pkg, rel, doc.body, index)
        body = _with_nav(body, _nav(pkg, doc, docs, refs))
        if not body.endswith("\n"):
            body += "\n"
        new = doc.front + body
        raw = _read_raw(doc.path)
        if raw is not None and "\r\n" in raw:  # keep a CRLF file CRLF, so a link change isn't a whole-file diff
            new = new.replace("\r\n", "\n").replace("\n", "\r\n")
        if new != raw:
            changed.append(rel)
            if not check:
                _write_raw(doc.path, new)
    readme = pkg.path_of("planning/README.md")
    content = _index_md(pkg, docs, index)
    if not readme.is_file() or readme.read_text(encoding="utf-8") != content:
        changed.append("planning/README.md")
        if not check:
            readme.parent.mkdir(parents=True, exist_ok=True)
            readme.write_text(content, encoding="utf-8", newline="\n")
    return changed + (sync_blocks(pkg, check=check, adopt_unmarked=adopt and not check) if commands else [])
