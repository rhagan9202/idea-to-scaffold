class PackageError(Exception):
    """Raised when a package cannot be read at all."""


def templates_dir() -> Path:
    """Path to the bundled templates folder."""
    return Path(str(resources.files("idea_to_scaffold") / "templates"))


def blank_package_dir() -> Path:
    return templates_dir() / "package"


def parse_front_matter(text: str) -> tuple[dict[str, Any], str]:
    """Split a Markdown document into (front matter dict, body)."""
    match = FRONT_MATTER_RE.match(text)
    if not match:
        return {}, text
    try:
        data = yaml.safe_load(match.group(1)) or {}
    except yaml.YAMLError:
        data = {}
    if not isinstance(data, dict):
        data = {}
    return data, text[match.end():]


@dataclass
class Package:
    root: Path
    manifest: dict[str, Any] = field(default_factory=dict)

    @classmethod
    def load(cls, root: Path) -> "Package":
        root = Path(root)
        manifest_path = root / "package.yaml"
        if not manifest_path.is_file():
            raise PackageError(f"no package.yaml in {root}")
        try:
            manifest = yaml.safe_load(manifest_path.read_text(encoding="utf-8")) or {}
        except yaml.YAMLError as exc:
            raise PackageError(f"package.yaml is not valid YAML: {exc}") from exc
        if not isinstance(manifest, dict):
            raise PackageError("package.yaml must be a mapping")
        return cls(root=root, manifest=manifest)

    # --- manifest helpers -------------------------------------------------
    def get(self, dotted: str, default: Any = None) -> Any:
        node: Any = self.manifest
        for part in dotted.split("."):
            if not isinstance(node, dict) or part not in node:
                return default
            node = node[part]
        return node

    @property
    def name(self) -> str:
        return str(self.get("project.name", ""))

    @property
    def slug(self) -> str:
        return str(self.get("project.slug", ""))

    @property
    def summary(self) -> str:
        return str(self.get("project.summary", ""))

    @property
    def language(self) -> str:
        return str(self.get("stack.language", "")).lower()

    @property
    def agents(self) -> list[str]:
        agents = self.get("agents") or ["codex", "claude", "copilot", "cursor"]
        return [str(a).lower() for a in agents]

    @property
    def commands(self) -> dict[str, str]:
        cmds = self.get("commands") or {}
        return {k: str(v) for k, v in cmds.items() if v}

    # --- files ------------------------------------------------------------
    def markdown_files(self, sub: str) -> list[Path]:
        base = self.root / sub
        if not base.is_dir():
            return []
        return sorted(p for p in base.rglob("*.md") if p.is_file())

    def planning_files(self) -> list[Path]:
        return self.markdown_files("planning")

    def playbooks(self) -> list[Path]:
        return self.markdown_files("playbooks")

    def rel(self, path: Path) -> str:
        return path.relative_to(self.root).as_posix()

    def status_of(self, rel_path: str) -> str | None:
        path = self.root / rel_path
        if path.is_file():
            fm, _ = parse_front_matter(path.read_text(encoding="utf-8"))
            if "status" in fm:
                return str(fm["status"])
        artifacts = self.get("artifacts") or {}
        value = artifacts.get(rel_path)
        return str(value) if value is not None else None
